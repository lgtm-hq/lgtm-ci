#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
# Purpose: Generate the read-only and overlay variants of each facade reusable (or check them) (#1081, #1356)
#
# Usage:
#   bash scripts/ci/workflows/sync-readonly-variants.sh           # rewrite in place
#   bash scripts/ci/workflows/sync-readonly-variants.sh --check   # exit 1 on drift
#
# GitHub validates the permission union of a reusable workflow before any job
# `if:` runs, so a caller of a facade that can publish must grant the publish
# scopes even when it never publishes. A facade opts into a read-only variant
# with one marker line, conventionally inside the omit region that holds the
# facade's own header comment so the variant does not inherit it:
#
#   # lgtm-ci-readonly:omit:begin
#   # lgtm-ci-readonly-variant: reusable-test-node-run.yml
#   # lgtm-ci-readonly:omit:end
#
# and wraps each mutation-only region (the publish job, inputs and env lines
# only that job needs) in the same begin/end pair. A variant that still
# carried the marker would be rejected rather than treated as a facade.
#
# The variant is the facade with the lines before `---` replaced by the
# generated header below, the omitted regions dropped and ` (read-only)`
# appended to the first top-level `name:` (plain or double-quoted scalar
# without a trailing comment; anything else is an error). Everything else, job ids and job names
# included, is copied verbatim, so the variant reports the same check names
# under the caller's job id and cannot drift from the facade's behaviour. The
# facade itself is never rewritten and keeps calling its jobs inline: nesting
# them under a facade job would add a segment to every check name that org
# rulesets require. The BATS contract test runs `--check`; after editing a
# facade, run this script and commit the variant with it.
#
# Overlay variant (#1356). A facade may also declare one variant that differs
# by more than removed lines, with a second marker line (the overlay variant
# drops both marker lines; keep this one inside a readonly omit region so the
# read-only variant does not carry it):
#
#   # lgtm-ci-overlay-variant: reusable-test-node-custom.yml
#
# The lines that differ sit in named regions of the facade:
#
#   # lgtm-ci-overlay:<slot>:begin
#   ...facade-only lines...
#   # lgtm-ci-overlay:<slot>:end
#
# and the overlay file $OVERLAYS_DIR/<variant without .yml>.overlay holds
# the variant's lines for every slot, each after a column-0 `@@ <slot>` line
# (an empty slot drops the region). Lines before the first `@@` are the
# overlay's own comments; trailing blank lines of a slot are dropped, so keep
# a blank line the variant needs outside the region. The overlay variant is
# the facade with the lines before `---` replaced by the generated header,
# each region replaced by its slot, the two variant marker lines dropped and
# the readonly omit markers dropped (their lines kept); nothing is renamed. Every slot is used exactly once and every
# region has a slot. The read-only variant drops the overlay marker lines and
# keeps what they enclose. Shared lines thus have one source, the facade, and
# variant-only lines have one, the overlay.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="${REPO_ROOT:-$(cd "$SCRIPT_DIR/../../.." && pwd)}"
WORKFLOWS_DIR="${WORKFLOWS_DIR:-$REPO_ROOT/.github/workflows}"

VARIANT_MARK="# lgtm-ci-readonly-variant:"
OMIT_BEGIN="# lgtm-ci-readonly:omit:begin"
OMIT_END="# lgtm-ci-readonly:omit:end"
GENERATED_MARK="# GENERATED by scripts/ci/workflows/sync-readonly-variants.sh"
OVERLAY_VARIANT_MARK="# lgtm-ci-overlay-variant:"
OVERLAYS_DIR="${OVERLAYS_DIR:-$(dirname "$WORKFLOWS_DIR")/workflow-overlays}"

check=0
case "${1:-}" in
"") ;;
--check) check=1 ;;
*)
	echo "usage: $0 [--check]" >&2
	exit 2
	;;
esac

# Print the variant for one facade on stdout; exit 1 on unbalanced markers.
render_variant() {
	local facade="$1"
	local facade_name
	facade_name="$(basename "$facade")"
	cat <<EOF
$GENERATED_MARK from
# $facade_name — do not edit. Edit the facade, then re-run the script.
#
# Read-only variant (#1081): the facade's jobs without its mutation jobs, so
# the permission union a caller must grant holds no write scope. Job ids and
# names match the facade, so check names under the caller's job id do too.
# Results stay in this call's artifacts (results.v1, #1080); see
# docs/reusable-workflows.md "Read-only variants" to publish them separately.
EOF
	# Markers match whole lines only (indentation aside), so prose that
	# mentions a marker is copied, not treated as one. Kept lines are copied
	# verbatim (block scalars included); a variant that would end in a blank
	# line fails instead, and the facade moves that blank line into the omit
	# region it separates.
	awk -v omit_begin="$OMIT_BEGIN" -v omit_end="$OMIT_END" -v facade="$facade_name" '
		function is_marker(line, mark) { sub(/^[ \t]+/, "", line); sub(/[ \t]+$/, "", line); return line == mark }
		function is_overlay_marker(line) { return line ~ /^[ \t]*# lgtm-ci-overlay:[a-z0-9-]+:(begin|end)[ \t]*$/ }
		function out(line) { print line; last_blank = (line ~ /^[ \t]*$/) }
		!started { if ($0 == "---") { started = 1; print } ; next }
		is_marker($0, omit_begin) {
			if (omitting) { printf "%s:%d: nested %s\n", facade, NR, omit_begin > "/dev/stderr"; bad = 1 }
			omitting = 1; next
		}
		is_marker($0, omit_end) {
			if (!omitting) { printf "%s:%d: %s without begin\n", facade, NR, omit_end > "/dev/stderr"; bad = 1 }
			omitting = 0; next
		}
		omitting { next }
		is_overlay_marker($0) { next }
		/^name: / && !renamed {
			renamed = 1
			if ($0 ~ /^name: [^"\047#|> ]([^#]*[^ #])?$/) { out($0 " (read-only)"); next }
			if ($0 ~ /^name: "[^"#]*"$/) { sub(/"$/, " (read-only)\""); out($0); next }
			printf "%s:%d: cannot rename this name: form; use a plain or double-quoted scalar\n", facade, NR > "/dev/stderr"
			bad = 1; next
		}
		{ out($0) }
		END {
			if (!started) { printf "%s: no --- document start\n", facade > "/dev/stderr"; bad = 1 }
			if (omitting) { printf "%s: unterminated %s\n", facade, omit_begin > "/dev/stderr"; bad = 1 }
			if (!renamed) { printf "%s: no top-level name:\n", facade > "/dev/stderr"; bad = 1 }
			if (last_blank) { printf "%s: variant would end in a blank line; move it inside the final omit region\n", facade > "/dev/stderr"; bad = 1 }
			exit bad
		}
	' "$facade"
}

# Print the overlay variant of one facade on stdout; exit 1 on a bad region,
# a missing or unused slot, or a malformed overlay file.
render_overlay_variant() {
	local facade="$1" overlay="$2"
	local facade_name overlay_name
	facade_name="$(basename "$facade")"
	overlay_name="${overlay#"$REPO_ROOT"/}"
	cat <<EOF
$GENERATED_MARK from
# $facade_name and $overlay_name — do not edit.
# Edit the facade (shared lines) or the overlay (variant-only lines), then
# re-run the script.
#
# Overlay variant (#1356): the facade with each lgtm-ci-overlay region
# replaced by the overlay's slot of the same name; see
# docs/reusable-workflows.md "Overlay variants".
EOF
	# Pass 1 reads the overlay's slots, pass 2 copies the facade. Markers
	# match whole lines only, as for the read-only variant.
	awk -v omit_begin="$OMIT_BEGIN" -v omit_end="$OMIT_END" -v facade="$facade_name" -v overlay="$overlay_name" '
		function is_marker(line, mark) { sub(/^[ \t]+/, "", line); sub(/[ \t]+$/, "", line); return line == mark }
		function region(line, kind,   t) {
			t = line; sub(/^[ \t]+/, "", t); sub(/[ \t]+$/, "", t)
			if (t !~ /^# lgtm-ci-overlay:[a-z0-9-]+:(begin|end)$/) return ""
			if (t !~ (":" kind "$")) return ""
			sub(/^# lgtm-ci-overlay:/, "", t); sub(/:(begin|end)$/, "", t)
			return t
		}
		function out(line) { print line; last_blank = (line ~ /^[ \t]*$/) }
		function close_slot() {
			if (slot == "") return
			# Trailing blank lines separate slots in the overlay; they are not content.
			while (count[slot] > 0 && body[slot, count[slot]] ~ /^[ \t]*$/) count[slot]--
		}
		FNR == NR {
			if ($0 ~ /^@@/) {
				close_slot()
				slot = ""
				if ($0 !~ /^@@ [a-z0-9-]+$/) { printf "%s:%d: malformed slot line; use @@ <slot>\n", overlay, FNR > "/dev/stderr"; bad = 1; next }
				slot = substr($0, 4)
				if (slot in defined) { printf "%s:%d: slot %s defined twice\n", overlay, FNR, slot > "/dev/stderr"; bad = 1 }
				defined[slot] = FNR; count[slot] = 0; order[++slots] = slot
				next
			}
			if (slot != "") body[slot, ++count[slot]] = $0
			next
		}
		FNR == 1 { close_slot() }
		!started { if ($0 == "---") { started = 1; print } ; next }
		(name = region($0, "begin")) != "" {
			if (inside != "") { printf "%s:%d: overlay region %s opened inside %s\n", facade, FNR, name, inside > "/dev/stderr"; bad = 1 }
			inside = name
			if (!(name in defined)) { printf "%s:%d: overlay region %s has no slot in %s\n", facade, FNR, name, overlay > "/dev/stderr"; bad = 1; next }
			if (name in used) { printf "%s:%d: overlay region %s used twice\n", facade, FNR, name > "/dev/stderr"; bad = 1; next }
			used[name] = FNR
			for (i = 1; i <= count[name]; i++) out(body[name, i])
			next
		}
		(name = region($0, "end")) != "" {
			if (inside != name) { printf "%s:%d: overlay region end %s does not close %s\n", facade, FNR, name, (inside == "" ? "any region" : inside) > "/dev/stderr"; bad = 1 }
			inside = ""; next
		}
		inside != "" { next }
		is_marker($0, omit_begin) || is_marker($0, omit_end) { next }
		/^# lgtm-ci-(readonly|overlay)-variant:/ { next }
		{ out($0) }
		END {
			if (!started) { printf "%s: no --- document start\n", facade > "/dev/stderr"; bad = 1 }
			if (inside != "") { printf "%s: unterminated overlay region %s\n", facade, inside > "/dev/stderr"; bad = 1 }
			for (i = 1; i <= slots; i++) if (!(order[i] in used)) { printf "%s:%d: slot %s matches no region in %s\n", overlay, defined[order[i]], order[i], facade > "/dev/stderr"; bad = 1 }
			if (last_blank) { printf "%s: overlay variant would end in a blank line\n", facade > "/dev/stderr"; bad = 1 }
			exit bad
		}
	' "$overlay" "$facade"
}

# Compare or write one rendered variant; in --check mode record drift under
# its kind (drifted or drifted_overlay).
publish_variant() {
	local variant="$1" updated="$2" kind="$3"
	if [[ -f "$variant" ]] && cmp -s "$variant" "$updated"; then
		rm -f "$updated"
		return 0
	fi
	if ((check)); then
		if [[ "$kind" == drifted_overlay ]]; then
			drifted_overlay+=("$(basename "$variant")")
		else
			drifted+=("$(basename "$variant")")
		fi
		rm -f "$updated"
	else
		mv "$updated" "$variant"
		echo "wrote $(basename "$variant")"
	fi
}

# Refuse a variant name that is malformed, names the facade itself, would
# overwrite a hand-maintained workflow, or another marker already claims; a
# mistaken marker must fail, not replace a public entry point.
claim_variant() {
	local facade="$1" variant_name="$2" want
	if [[ ! "$variant_name" =~ ^reusable-[A-Za-z0-9._-]+\.yml$ ]]; then
		echo "$(basename "$facade"): invalid variant name '$variant_name'" >&2
		return 1
	fi
	if [[ "$variant_name" == "$(basename "$facade")" ]]; then
		echo "$(basename "$facade"): variant name is the facade itself" >&2
		return 1
	fi
	if [[ -f "$WORKFLOWS_DIR/$variant_name" ]] && ! grep -qF "$GENERATED_MARK" "$WORKFLOWS_DIR/$variant_name"; then
		echo "$(basename "$facade"): $variant_name exists and is not generated; refusing to overwrite it" >&2
		return 1
	fi
	for want in "${expected[@]+"${expected[@]}"}"; do
		if [[ "$want" == "$variant_name" ]]; then
			echo "$(basename "$facade"): $variant_name is already the variant of another facade" >&2
			return 1
		fi
	done
	expected+=("$variant_name")
}

status=0
drifted=()
drifted_overlay=()
expected=()
overlays_claimed=()
for facade in "$WORKFLOWS_DIR"/reusable-*.yml; do
	if grep -qF "$GENERATED_MARK" "$facade"; then
		# A generated file is never a facade; one still carrying a marker
		# means the facade left it outside every omit region.
		for mark in "$VARIANT_MARK" "$OVERLAY_VARIANT_MARK"; do
			if grep -q "^${mark}" "$facade"; then
				echo "$(basename "$facade"): generated variant carries ${mark}; wrap it in an omit region" >&2
				status=1
			fi
		done
		continue
	fi
	# A marker must start in column 0; an indented one would otherwise skip
	# generation silently.
	for mark in "$VARIANT_MARK" "$OVERLAY_VARIANT_MARK"; do
		if grep -q "^[[:space:]]\{1,\}${mark}" "$facade"; then
			echo "$(basename "$facade"): ${mark} must start in column 0" >&2
			status=1
		fi
	done

	variant_name="$(sed -n "s/^${VARIANT_MARK} *//p" "$facade" | head -n 1)"
	if [[ -n "$variant_name" ]]; then
		if claim_variant "$facade" "$variant_name"; then
			updated="$(mktemp)"
			if render_variant "$facade" >"$updated"; then
				publish_variant "$WORKFLOWS_DIR/$variant_name" "$updated" drifted
			else
				rm -f "$updated"
				status=1
			fi
		else
			status=1
		fi
	fi

	if (($(grep -c "^${OVERLAY_VARIANT_MARK}" "$facade") > 1)); then
		echo "$(basename "$facade"): more than one ${OVERLAY_VARIANT_MARK} line; a facade has one overlay variant" >&2
		status=1
		continue
	fi
	overlay_name="$(sed -n "s/^${OVERLAY_VARIANT_MARK} *//p" "$facade" | head -n 1)"
	[[ -n "$overlay_name" ]] || continue
	claim_variant "$facade" "$overlay_name" || {
		status=1
		continue
	}
	overlay="$OVERLAYS_DIR/${overlay_name%.yml}.overlay"
	overlays_claimed+=("$(basename "$overlay")")
	if [[ ! -f "$overlay" ]]; then
		echo "$(basename "$facade"): overlay ${overlay#"$REPO_ROOT"/} for $overlay_name is missing" >&2
		status=1
		continue
	fi
	updated="$(mktemp)"
	if render_overlay_variant "$facade" "$overlay" >"$updated"; then
		publish_variant "$WORKFLOWS_DIR/$overlay_name" "$updated" drifted_overlay
	else
		rm -f "$updated"
		status=1
	fi
done

# A generated variant whose facade lost its marker is an orphan: it would
# keep serving a stale copy of the facade. So is an overlay no facade names.
orphans=()
for workflow in "$WORKFLOWS_DIR"/*.yml; do
	grep -qF "$GENERATED_MARK" "$workflow" || continue
	name="$(basename "$workflow")"
	found=0
	for want in "${expected[@]+"${expected[@]}"}"; do
		[[ "$want" == "$name" ]] && found=1
	done
	((found)) || orphans+=("$name")
done
orphan_overlays=()
for overlay in "$OVERLAYS_DIR"/*.overlay; do
	[[ -f "$overlay" ]] || continue
	name="$(basename "$overlay")"
	found=0
	for want in "${overlays_claimed[@]+"${overlays_claimed[@]}"}"; do
		[[ "$want" == "$name" ]] && found=1
	done
	((found)) || orphan_overlays+=("$name")
done

if ((${#drifted[@]})); then
	printf 'read-only variant out of date: %s\n' "${drifted[@]}" >&2
fi
if ((${#drifted_overlay[@]})); then
	printf 'overlay variant out of date: %s\n' "${drifted_overlay[@]}" >&2
fi
if ((${#drifted[@]} + ${#drifted_overlay[@]})); then
	echo "run: bash scripts/ci/workflows/sync-readonly-variants.sh" >&2
	status=1
fi
if ((${#orphans[@]})); then
	printf 'generated variant without a facade marker: %s\n' "${orphans[@]}" >&2
	status=1
fi
if ((${#orphan_overlays[@]})); then
	printf 'overlay without a facade marker: %s\n' "${orphan_overlays[@]}" >&2
	status=1
fi
exit "$status"
