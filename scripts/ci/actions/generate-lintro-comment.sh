#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
# Purpose: Generate quality summary markdown for lintro analysis results
#
# Environment variables expected:
#   LINTRO_OUTPUT - Path to lintro check output file
#   LINTRO_EXIT_CODE - Exit code from lintro check
#   GITHUB_RUN_ID - GitHub Actions run ID
#   GITHUB_REPOSITORY - Repository name
#   GITHUB_SERVER_URL - GitHub server URL
#   COMMENT_OUTPUT - Path to write the comment body to (optional)
#
# Outputs (when GITHUB_OUTPUT is set):
#   history-summary - Issue count for the comment's run history (#1346)

set -euo pipefail

# Defaults
LINTRO_OUTPUT="${LINTRO_OUTPUT:-chk-output.txt}"
LINTRO_EXIT_CODE="${LINTRO_EXIT_CODE:-0}"

# Determine status using score_emoji if available for consistency
if [[ "$LINTRO_EXIT_CODE" =~ ^[0-9]+$ ]] && [[ "$LINTRO_EXIT_CODE" -eq 0 ]]; then
	STATUS_EMOJI="✅"
	STATUS_TEXT="PASSED"
else
	STATUS_EMOJI="⚠️"
	STATUS_TEXT="ISSUES FOUND"
fi

# Build URL (use safe default for GITHUB_REPOSITORY to avoid double slashes)
REPO="${GITHUB_REPOSITORY:-unknown/unknown}"
BUILD_URL="${GITHUB_SERVER_URL:-https://github.com}/${REPO}/actions/runs/${GITHUB_RUN_ID:-0}"

# Extract execution summary from output
SUMMARY=""
if [[ -f "$LINTRO_OUTPUT" ]] && [[ -s "$LINTRO_OUTPUT" ]]; then
	# Try to extract from the EXECUTION SUMMARY section regardless of emoji
	start_line=$(grep -n "EXECUTION SUMMARY" "$LINTRO_OUTPUT" | head -n1 | cut -d: -f1 || true)
	if [[ -n "${start_line:-}" ]]; then
		SUMMARY=$(tail -n +"$start_line" "$LINTRO_OUTPUT")
	else
		# Fallback to last 50 lines to capture table if header not found
		SUMMARY=$(tail -n 50 "$LINTRO_OUTPUT")
	fi
else
	SUMMARY="No lintro output available — file missing or empty"
fi

# Sanitize SUMMARY to prevent triple-backtick breakout in fenced code block
SUMMARY="${SUMMARY//\`\`\`/~~~}"

COMMENT_BODY="$(
	cat <<EOF
## Lintro Code Quality Analysis

This PR has been analyzed using **lintro** - our unified code quality tool.

Checks run inside the pinned **py-lintro** container (same as the workflow quality job), so the summary reflects the full bundled toolchain.

### Status: ${STATUS_EMOJI} ${STATUS_TEXT}

**Workflow:**
1. Performed code quality checks with \`lintro chk\` (Docker)

### Results:
\`\`\`
${SUMMARY}
\`\`\`

---

[View full build details](${BUILD_URL})

<sub>Generated by lintro analysis workflow</sub>
EOF
)"

# Issue count shown on this run's entry once the comment archives it (#1346),
# read from the "Total Issues" row of lintro's TOTALS table.
HISTORY_SUMMARY="${STATUS_TEXT,,}"
TOTAL_ISSUES=""
if [[ -f "$LINTRO_OUTPUT" ]]; then
	# Strip ANSI colour codes first so their digits are not read as the count.
	TOTAL_ISSUES=$(sed $'s/\033\\[[0-9;]*m//g' "$LINTRO_OUTPUT" | grep -m1 'Total Issues' |
		grep -oE '[0-9]+' | tail -n1 || true)
fi
if [[ -n "$TOTAL_ISSUES" ]]; then
	if [[ "$TOTAL_ISSUES" == "1" ]]; then
		HISTORY_SUMMARY="1 issue"
	else
		HISTORY_SUMMARY="${TOTAL_ISSUES} issues"
	fi
fi
if [[ -n "${GITHUB_OUTPUT:-}" ]]; then
	echo "history-summary=${HISTORY_SUMMARY}" >>"$GITHUB_OUTPUT"
fi

if [[ -n "${COMMENT_OUTPUT:-}" ]]; then
	printf '%s\n' "$COMMENT_BODY" >"$COMMENT_OUTPUT"
else
	printf '%s\n' "$COMMENT_BODY"
fi
