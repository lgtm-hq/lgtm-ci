#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
# Purpose: Generate Lighthouse audit summary markdown from CI results
#
# Required environment variables:
#   RESULTS_PATH - Path to Lighthouse results JSON file or directory
#   REPORT_URL - URL to full report (optional)
#   THRESHOLD_PERFORMANCE - Minimum performance score
#   THRESHOLD_ACCESSIBILITY - Minimum accessibility score
#   THRESHOLD_BEST_PRACTICES - Minimum best practices score
#   THRESHOLD_SEO - Minimum SEO score
#
# The report URL is a caller input: it is linked only when it is a plain
# HTTPS URL (#1676, docs/comment-sanitize.md). Thresholds are validated as
# integers below; scores are numbers jq computed.

set -euo pipefail

# Source shared libraries for score_emoji and output helpers
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE:-$0}")" && pwd)"
LIB_DIR="$SCRIPT_DIR/../lib"

if [[ -f "$LIB_DIR/github/format.sh" ]]; then
	# shellcheck source=../lib/github/format.sh
	source "$LIB_DIR/github/format.sh"
fi

# Required: multi-line outputs go only through set_github_output_multiline
# (random delimiter, #1675).
# shellcheck source=../lib/github/output.sh
source "$LIB_DIR/github/output.sh"

# shellcheck source=../lib/github/comment_sanitize.sh
source "$LIB_DIR/github/comment_sanitize.sh"

: "${RESULTS_PATH:?RESULTS_PATH is required}"
: "${REPORT_URL:=}"
: "${THRESHOLD_PERFORMANCE:=80}"
: "${THRESHOLD_ACCESSIBILITY:=90}"
: "${THRESHOLD_BEST_PRACTICES:=80}"
: "${THRESHOLD_SEO:=80}"

SAFE_REPORT_URL="$(printf '%s' "$REPORT_URL" | comment_sanitize url)"
if [[ -z "$SAFE_REPORT_URL" && -n "${REPORT_URL//[[:space:]]/}" ]]; then
	echo "::warning::report-url is not a plain HTTPS URL with an ASCII host; the link is left out of the Lighthouse report"
fi

GENERATED_DATE=$(date -u +%Y-%m-%d)
COMMIT_LINE="- **Commit:** unknown"
if declare -f format_github_commit_line &>/dev/null; then
	COMMIT_LINE=$(format_github_commit_line)
fi
BUILD_URL=""
if declare -f get_github_actions_run_url &>/dev/null; then
	BUILD_URL=$(get_github_actions_run_url || true)
fi

# Validate and normalize threshold variables
# Strip trailing %, whitespace, ensure numeric integer in 0-100 range
validate_threshold() {
	local name="$1"
	local value="$2"
	# Strip whitespace and trailing %
	value="${value%\%}"
	value="${value// /}"
	# Check if numeric integer
	if ! [[ "$value" =~ ^[0-9]+$ ]]; then
		echo "::error::$name must be a numeric integer, got: '$value'"
		exit 1
	fi
	# Check range
	if [[ "$value" -lt 0 || "$value" -gt 100 ]]; then
		echo "::error::$name must be between 0 and 100, got: $value"
		exit 1
	fi
	echo "$value"
}

THRESHOLD_PERFORMANCE=$(validate_threshold "THRESHOLD_PERFORMANCE" "$THRESHOLD_PERFORMANCE")
THRESHOLD_ACCESSIBILITY=$(validate_threshold "THRESHOLD_ACCESSIBILITY" "$THRESHOLD_ACCESSIBILITY")
THRESHOLD_BEST_PRACTICES=$(validate_threshold "THRESHOLD_BEST_PRACTICES" "$THRESHOLD_BEST_PRACTICES")
THRESHOLD_SEO=$(validate_threshold "THRESHOLD_SEO" "$THRESHOLD_SEO")

# Find the results file
# Sort for deterministic selection when directory contains multiple JSON files
if [[ -d "$RESULTS_PATH" ]]; then
	RESULTS_FILE=$(find "$RESULTS_PATH" -name "*.json" -type f | sort | head -1)
else
	RESULTS_FILE="$RESULTS_PATH"
fi

if [[ ! -f "$RESULTS_FILE" ]]; then
	echo "::error::Lighthouse results not found at $RESULTS_PATH"
	# Still fails closed, and now says so in the comment (#1692): no scores,
	# never 0, and passed=false. The path is a caller input and stays in the
	# log only.
	BODY="## 🚦 Lighthouse CI Performance Report

This PR has been analyzed using **lgtm-ci** - our Lighthouse CI performance workflow.

### 📊 Status: ⚠️ MISSING

**Build:** ⚠️ No Lighthouse results found

**Status:** Lighthouse results were not generated, so no score could be checked.

### 📋 Report Details
- **Generated:** ${GENERATED_DATE}
${COMMIT_LINE}"
	if [[ -n "$BUILD_URL" ]]; then
		BODY="${BODY}

---

[View full build details](${BUILD_URL})"
	fi
	BODY="${BODY}

<sub>Generated by lgtm-ci Lighthouse CI workflow</sub>"
	echo "passed=false" >>"$GITHUB_OUTPUT"
	set_github_output_multiline "body" "$BODY"
	exit 1
fi

# Extract scores (multiply by 100 for percentage). Lighthouse writes a score
# from 0 to 1; one that is not such a number (null for a category that
# errored, absent, or out of range such as 1.5, which would read as 150) is
# unreadable (#1676, #1692): it fails the check and the comment says so
# instead of showing a score.
_score() {
	jq -r --arg c "$1" \
		'try (.categories[$c].score | if type == "number" and . >= 0 and . <= 1 then . * 100 | floor else error end) catch "invalid"' \
		"$RESULTS_FILE" 2>/dev/null || true
}
comment_read_count PERF "performance score" "$(_score performance)"
comment_read_count A11Y "accessibility score" "$(_score accessibility)"
comment_read_count BP "best-practices score" "$(_score best-practices)"
comment_read_count SEO "seo score" "$(_score seo)"

# Check thresholds; an unreadable score is never a pass.
PASSED=true
((${#COMMENT_UNREADABLE[@]} == 0)) || PASSED=false
[[ $PERF -lt $THRESHOLD_PERFORMANCE ]] && PASSED=false
[[ $A11Y -lt $THRESHOLD_ACCESSIBILITY ]] && PASSED=false
[[ $BP -lt $THRESHOLD_BEST_PRACTICES ]] && PASSED=false
[[ $SEO -lt $THRESHOLD_SEO ]] && PASSED=false

{
	echo "performance=$PERF"
	echo "accessibility=$A11Y"
	echo "best-practices=$BP"
	echo "seo=$SEO"
	echo "passed=$PASSED"
} >>"$GITHUB_OUTPUT"

# Fallback score_emoji if library not available
if ! declare -f score_emoji &>/dev/null; then
	score_emoji() {
		local score=$1
		local threshold=$2
		local warn=$((threshold - 10))
		((warn < 0)) && warn=0
		if [[ $score -ge $threshold ]]; then
			echo "🟢"
		elif [[ $score -ge $warn ]]; then
			echo "🟡"
		else echo "🔴"; fi
	}
fi

# Score cell: emoji and score, or unreadable.
score_cell() {
	local label="$1" score="$2" threshold="$3"
	if [[ " ${COMMENT_UNREADABLE[*]} " == *" ${label} "* ]]; then
		printf '%s' "⚠️ unreadable"
	else
		printf '%s' "$(score_emoji "$score" "$threshold") ${score}"
	fi
}
UNREADABLE_NOTES=""
if ((${#COMMENT_UNREADABLE[@]} > 0)); then
	UNREADABLE_NOTES=$'\n\n'"$(comment_unreadable_lines)"
fi

# Generate comment body
if ((${#COMMENT_UNREADABLE[@]} > 0)); then
	STATUS_EMOJI="⚠️"
	STATUS_TEXT="UNREADABLE"
	BUILD_STATUS="⚠️ Some Lighthouse scores are not numbers"
	SCORE_STATUS="Some scores could not be read; see the job log."
elif [[ "$PASSED" == "true" ]]; then
	STATUS_EMOJI="✅"
	STATUS_TEXT="PASSED"
	BUILD_STATUS="✅ Lighthouse CI passed"
	SCORE_STATUS="All scores meet thresholds."
else
	STATUS_EMOJI="⚠️"
	STATUS_TEXT="BELOW TARGET"
	BUILD_STATUS="⚠️ Some Lighthouse scores are below thresholds"
	SCORE_STATUS="Some scores are below thresholds."
fi

BODY="## 🚦 Lighthouse CI Performance Report

This PR has been analyzed using **lgtm-ci** - our Lighthouse CI performance workflow.

### 📊 Status: ${STATUS_EMOJI} ${STATUS_TEXT}

**Build:** ${BUILD_STATUS}

**Status:** ${SCORE_STATUS}

### 🚦 Performance Scores

| Category | Score | Threshold |
|----------|-------|-----------|
| **Performance** | $(score_cell "performance score" "$PERF" "$THRESHOLD_PERFORMANCE") | ${THRESHOLD_PERFORMANCE} |
| **Accessibility** | $(score_cell "accessibility score" "$A11Y" "$THRESHOLD_ACCESSIBILITY") | ${THRESHOLD_ACCESSIBILITY} |
| **Best Practices** | $(score_cell "best-practices score" "$BP" "$THRESHOLD_BEST_PRACTICES") | ${THRESHOLD_BEST_PRACTICES} |
| **SEO** | $(score_cell "seo score" "$SEO" "$THRESHOLD_SEO") | ${THRESHOLD_SEO} |${UNREADABLE_NOTES}"

if [[ -n "$SAFE_REPORT_URL" ]]; then
	BODY="${BODY}

### 🔎 View Full Reports

Public Report:

- [View Lighthouse Reports](${SAFE_REPORT_URL})"
fi

BODY="${BODY}

### 📋 Report Details
- **Generated:** ${GENERATED_DATE}
${COMMIT_LINE}"

if [[ -n "$BUILD_URL" ]]; then
	BODY="${BODY}

---

[View full build details](${BUILD_URL})"
fi

BODY="${BODY}

<sub>Generated by lgtm-ci Lighthouse CI workflow</sub>"

set_github_output_multiline "body" "$BODY"
