#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
# Purpose: Generate Playwright test summary markdown from test results
#
# Required environment variables:
#   RESULTS_PATH - Path to Playwright JSON results file
#   REPORT_URL - URL to full report (optional)
#   SHOW_FAILED - Whether to show failed tests list
#   MAX_FAILED - Maximum number of failed tests to show
#
# Untrusted text (#1676): failed test names come from the report and go into
# a sanitised code fence; the report URL is linked only when it is a plain
# HTTPS URL (docs/comment-sanitize.md).

set -euo pipefail

# Source shared libraries for formatting and output helpers
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE:-$0}")" && pwd)"
LIB_DIR="$SCRIPT_DIR/../lib"

if [[ -f "$LIB_DIR/github/format.sh" ]]; then
	# shellcheck source=../lib/github/format.sh
	source "$LIB_DIR/github/format.sh"
fi

# Required: multi-line outputs go only through set_github_output_multiline
# (random delimiter, #1675).
# shellcheck source=../lib/github/output.sh
source "$LIB_DIR/github/output.sh"

# shellcheck source=../lib/github/comment_sanitize.sh
source "$LIB_DIR/github/comment_sanitize.sh"

# PLAYWRIGHT_JQ_DEFS: the one rule for walking and classifying the tests of a
# Playwright JSON report (shared with parse_playwright_json and the e2e merge).
# shellcheck source=../lib/testing/parse/playwright.sh
source "$LIB_DIR/testing/parse/playwright.sh"

# Test-level statuses listed (and, without stats, counted) as failed. A native
# report marks a failed test "unexpected"; failed/timedOut/interrupted are the
# older and per-attempt spellings. Flaky is reported on its own row.
# shellcheck disable=SC2016 # jq program, not shell
COMMENT_JQ_DEFS="${PLAYWRIGHT_JQ_DEFS}"'
def comment_failed_status:
	. == "unexpected" or . == "failed" or . == "timedOut" or . == "interrupted";
def comment_known_status:
	type == "string"
	and (pw_passed_status or comment_failed_status or pw_skipped_status or . == "flaky");
def comment_spec_bad:
	if type != "object" or (.tests | type) != "array" then 1
	elif .ok == false
		and ([.tests[] | select(type == "object" and (.status | type == "string")
			and (.status | comment_failed_status))] | length) == 0
	then 1
	else 0 end;
def comment_suite_bad:
	if type != "object" then 1
	else (if has("suites") then (.suites | if type == "array" then (map(comment_suite_bad) | add // 0) else 1 end) else 0 end)
		+ (if has("specs") then (.specs | if type == "array" then (map(comment_spec_bad) | add // 0) else 1 end) else 0 end)
		+ (if has("tests") and (.tests | type) != "array" then 1 else 0 end)
	end;
def comment_bad_containers: .suites | map(comment_suite_bad) | add // 0;
'

: "${RESULTS_PATH:=playwright-report/results.json}"
: "${REPORT_URL:=}"
: "${SHOW_FAILED:=true}"
: "${MAX_FAILED:=10}"
STRUCTURE_NOTES=""
if [[ ! "$MAX_FAILED" =~ ^[0-9]+$ ]]; then
	echo "::warning title=Playwright comment::max-failed-tests must be a whole number, got '${MAX_FAILED}'; using 10" >&2
	MAX_FAILED=10
fi

SAFE_REPORT_URL="$(printf '%s' "$REPORT_URL" | comment_sanitize url)"
if [[ -z "$SAFE_REPORT_URL" && -n "${REPORT_URL//[[:space:]]/}" ]]; then
	echo "::warning::report-url is not a plain HTTPS URL with an ASCII host; the link is left out of the Playwright report"
fi

GENERATED_DATE=$(date -u +%Y-%m-%d)
COMMIT_LINE="- **Commit:** unknown"
if declare -f format_github_commit_line &>/dev/null; then
	COMMIT_LINE=$(format_github_commit_line)
fi
BUILD_URL=""
if declare -f get_github_actions_run_url &>/dev/null; then
	BUILD_URL=$(get_github_actions_run_url || true)
fi

# Check if results file exists
if [[ ! -f "$RESULTS_PATH" ]]; then
	echo "::warning::Playwright results not found at $RESULTS_PATH"
	BODY="## 🧪 Playwright E2E Test Report

This PR has been analyzed using **lgtm-ci** - our Playwright E2E test workflow.

### 📊 Status: ⚠️ MISSING

**Build:** ⚠️ No Playwright results found

**Status:** Playwright results were not generated.

### 🧪 Test Results

| Metric | Value |
|--------|-------|
| **Total Tests** | 0 |
| **Passed** | 0 |
| **Failed** | 0 |
| **Skipped** | 0 |
| **Pass Rate** | 0% |

### 📋 Report Details
- **Generated:** ${GENERATED_DATE}
${COMMIT_LINE}"

	if [[ -n "$BUILD_URL" ]]; then
		BODY="${BODY}

---

[View full build details](${BUILD_URL})"
	fi

	BODY="${BODY}

<sub>Generated by lgtm-ci Playwright E2E workflow</sub>"

	{
		echo "total=0"
		echo "passed=0"
		echo "failed=0"
		echo "skipped=0"
		echo "success=false"
	} >>"$GITHUB_OUTPUT"
	set_github_output_multiline "body" "$BODY"
	exit 0
fi

_count() { jq -r "${COMMENT_JQ_DEFS} $1" "$RESULTS_PATH" 2>/dev/null || echo "invalid"; }

# The suites, specs and test lists are checked before any count is trusted,
# with or without stats (#1692 review): a suite whose suites or specs is not
# a list, a spec without a test list, a spec that says ok: false with no
# failed test, or a test without a recognised status makes the result
# unknown. Sets UNKNOWN_STATUS, BAD_CONTAINERS and LISTED_FAILED, adds notes,
# and returns the number of problems found.
_check_suites() {
	UNKNOWN_STATUS=$(_count 'pw_count(comment_known_status | not)')
	BAD_CONTAINERS=$(_count 'comment_bad_containers')
	LISTED_FAILED=$(_count 'pw_count(comment_failed_status)')
	comment_read_count UNKNOWN_STATUS "tests without a status" "$UNKNOWN_STATUS"
	comment_read_count BAD_CONTAINERS "suites and specs" "$BAD_CONTAINERS"
	comment_read_count LISTED_FAILED "failed tests" "$LISTED_FAILED"
	local problems=0
	# Every test the walk finds needs a status this renderer knows (#1692): a
	# test with a failed attempt but no aggregate status is in no column, so
	# the result is unknown, never a pass of the tests that do have one.
	if ((UNKNOWN_STATUS > 0)); then
		echo "::warning::${UNKNOWN_STATUS} test(s) in the Playwright report have no recognised status; the comment says so" >&2
		STRUCTURE_NOTES+="⚠️ ${UNKNOWN_STATUS} test(s) in the report have no recognised \`status\`; see the job log."$'\n'
		problems=$((problems + 1))
	fi
	if ((BAD_CONTAINERS > 0)); then
		echo "::warning::${BAD_CONTAINERS} suite(s) or spec(s) in the Playwright report have no readable tests; the comment says so" >&2
		STRUCTURE_NOTES+="⚠️ ${BAD_CONTAINERS} suite(s) or spec(s) in the report have no readable \`tests\`, \`specs\` or \`suites\` list or test outcome; see the job log."$'\n'
		problems=$((problems + 1))
	fi
	return "$problems"
}

# Extract test counts from Playwright JSON report
if jq -e '.stats | type == "object"' "$RESULTS_PATH" >/dev/null 2>&1; then
	# Standard report format. Each field is read on its own and must be a
	# whole number (#1676): anything else (a string, a negative or fractional
	# value, or a field the format always writes being absent) is unreadable,
	# and the comment says so instead of a result. timedOut and interrupted
	# are older, optional fields: absent means 0.
	_stat() {
		jq -r --arg k "$1" --arg absent "$2" '.stats[$k] | if . == null then $absent else . end' \
			"$RESULTS_PATH" 2>/dev/null || echo "invalid"
	}
	comment_read_count EXPECTED "stats.expected" "$(_stat expected invalid)"
	comment_read_count UNEXPECTED "stats.unexpected" "$(_stat unexpected invalid)"
	comment_read_count TIMED_OUT "stats.timedOut" "$(_stat timedOut 0)"
	comment_read_count INTERRUPTED "stats.interrupted" "$(_stat interrupted 0)"
	comment_read_count SKIPPED "stats.skipped" "$(_stat skipped invalid)"
	comment_read_count FLAKY "stats.flaky" "$(_stat flaky invalid)"
	COUNTS_UNREADABLE=${#COMMENT_UNREADABLE[@]}
	# Include timedOut and interrupted in FAILED count (these are test failures)
	PASSED=$EXPECTED
	FAILED=$((UNEXPECTED + TIMED_OUT + INTERRUPTED))
	TOTAL=$((EXPECTED + FAILED + FLAKY + SKIPPED))
	# Playwright writes fractional milliseconds (e.g. 2374.609); bash compares
	# integers only, so round in jq, half-up as parse_playwright_json does.
	# A duration that is not a non-negative number is unreadable (N/A).
	DURATION=$(jq -r 'try (.stats.duration | if type == "number" and . >= 0 then (. + 0.5 | floor) else error end) catch "invalid"' "$RESULTS_PATH" 2>/dev/null || echo "invalid")
	comment_read_count DURATION "stats.duration" "$DURATION"
	# Every current Playwright writes stats beside suites: the suites are
	# checked too (#1692 review), and a stats count of failures below the
	# failed tests the suites list is a contradiction, so unknown, never a
	# pass. A stats-only summary (no suites) is read from stats as before.
	SUITES_TYPE=$(jq -r 'if has("suites") then (.suites | type) else "absent" end' "$RESULTS_PATH" 2>/dev/null || echo "invalid")
	if [[ "$SUITES_TYPE" == array ]]; then
		UNREADABLE_BEFORE=${#COMMENT_UNREADABLE[@]}
		SUITE_PROBLEMS=0
		_check_suites || SUITE_PROBLEMS=$?
		# A suite count jq could not read is unreadable too.
		COUNTS_UNREADABLE=$((COUNTS_UNREADABLE + SUITE_PROBLEMS + ${#COMMENT_UNREADABLE[@]} - UNREADABLE_BEFORE))
		if ((LISTED_FAILED > FAILED)); then
			echo "::warning::The Playwright report lists ${LISTED_FAILED} failed test(s) but its stats count ${FAILED}; the comment says so" >&2
			STRUCTURE_NOTES+="⚠️ The report lists ${LISTED_FAILED} failed test(s) but its \`stats\` count ${FAILED}; see the job log."$'\n'
			COUNTS_UNREADABLE=$((COUNTS_UNREADABLE + 1))
		fi
	elif [[ "$SUITES_TYPE" != absent ]]; then
		echo "::warning::The report's suites value is not a list; the comment says so" >&2
		COMMENT_UNREADABLE+=("suites")
		COUNTS_UNREADABLE=$((COUNTS_UNREADABLE + 1))
	fi
elif jq -e '.suites | type == "array"' "$RESULTS_PATH" >/dev/null 2>&1; then
	# No stats: count the tests in suites with the shared walk. Same columns as
	# the stats path: flaky on its own row, not in passed or failed.
	PASSED=$(_count 'pw_count(pw_passed_status)')
	FAILED=$(_count 'pw_count(comment_failed_status)')
	SKIPPED=$(_count 'pw_count(pw_skipped_status)')
	FLAKY=$(_count 'pw_count(. == "flaky")')
	comment_read_count PASSED "passed tests" "$PASSED"
	comment_read_count FAILED "failed tests" "$FAILED"
	comment_read_count SKIPPED "skipped tests" "$SKIPPED"
	comment_read_count FLAKY "flaky tests" "$FLAKY"
	SUITE_PROBLEMS=0
	_check_suites || SUITE_PROBLEMS=$?
	COUNTS_UNREADABLE=$((${#COMMENT_UNREADABLE[@]} + SUITE_PROBLEMS))
	TOTAL=$((PASSED + FAILED + SKIPPED + FLAKY + UNKNOWN_STATUS))
	DURATION=0
else
	# Not JSON, or neither a stats object nor a suites list (#1676): nothing
	# can be counted, so the counts are unreadable, never a pass with 0 tests.
	echo "::warning::The report's stats value is not a number; the comment says so" >&2
	COMMENT_UNREADABLE+=("stats")
	COUNTS_UNREADABLE=1
	PASSED=0
	FAILED=0
	SKIPPED=0
	FLAKY=0
	TOTAL=0
	DURATION=0
fi

# Errors outside any test (#1692 review): Playwright writes them to the
# top-level errors list for a global setup or config failure, a worker
# crash outside a test, or "No tests found", and fails the run itself. The
# counts it did report stay readable, so the result is FAILED, never PASSED
# or NO TESTS. A report without the list (older shapes) has none; a list
# that is present but not an array, null included, is unreadable.
REPORT_ERRORS=$(jq -r 'if type == "object" and has("errors") then
		(.errors | if type == "array" then length else "invalid" end) else 0 end' \
	"$RESULTS_PATH" 2>/dev/null || echo 0)
comment_read_count REPORT_ERRORS "errors" "$REPORT_ERRORS"
if [[ "$REPORT_ERRORS" == 0 && " ${COMMENT_UNREADABLE[*]} " == *" errors "* ]]; then
	COUNTS_UNREADABLE=$((COUNTS_UNREADABLE + 1))
fi
ERRORS_NOTE=""
if ((REPORT_ERRORS > 0)); then
	echo "::warning::The Playwright report lists ${REPORT_ERRORS} error(s) outside any test; the comment says so" >&2
	ERRORS_NOTE="❌ The report lists ${REPORT_ERRORS} error(s) outside any test (global setup, configuration or no tests found); see the job log."
fi

SUCCESS="true"
[[ $FAILED -gt 0 ]] && SUCCESS="false"
((REPORT_ERRORS == 0)) || SUCCESS="false"
# Unreadable counts are never a pass (#1676).
((COUNTS_UNREADABLE == 0)) || SUCCESS="false"

{
	echo "total=$TOTAL"
	echo "passed=$PASSED"
	echo "failed=$FAILED"
	echo "skipped=$SKIPPED"
	echo "success=$SUCCESS"
} >>"$GITHUB_OUTPUT"

# Calculate pass rate (use awk for float precision with small suites)
if [[ $TOTAL -gt 0 ]]; then
	# comment-safe: awk prints a fixed-point number of checked counts
	PASS_RATE=$(awk -v p="$PASSED" -v t="$TOTAL" 'BEGIN { printf "%.1f", (p*100)/t }')
else
	PASS_RATE=0
fi

# Format duration
if [[ $DURATION -gt 0 ]]; then
	DURATION_SEC=$(((DURATION + 500) / 1000))
	DURATION_STR="${DURATION_SEC}s"
else
	DURATION_STR="N/A"
fi

# Status emoji
if ((COUNTS_UNREADABLE > 0)); then
	STATUS_EMOJI="⚠️"
	STATUS_TEXT="UNKNOWN"
	TEST_STATUS_TEXT="⚠️ Test counts unreadable"
	FAILED_EMOJI=""
elif [[ "$SUCCESS" == "true" && $TOTAL -eq 0 ]]; then
	# A readable report with no tests is not a pass (#1676).
	STATUS_EMOJI="⚠️"
	STATUS_TEXT="NO TESTS"
	TEST_STATUS_TEXT="⚠️ No tests ran"
	FAILED_EMOJI=""
elif [[ "$SUCCESS" == "true" ]]; then
	STATUS_EMOJI="✅"
	STATUS_TEXT="PASSED"
	TEST_STATUS_TEXT="✅ Tests passed"
	FAILED_EMOJI=""
elif ((FAILED == 0 && REPORT_ERRORS > 0)); then
	STATUS_EMOJI="❌"
	STATUS_TEXT="FAILED"
	TEST_STATUS_TEXT="❌ The run reported errors outside any test"
	FAILED_EMOJI=""
else
	STATUS_EMOJI="❌"
	STATUS_TEXT="FAILED"
	TEST_STATUS_TEXT="❌ ${FAILED} test(s) failed"
	FAILED_EMOJI="❌"
fi

# Metrics table; unreadable counts replace it with what could not be read,
# and an unreadable duration is listed under it.
METRICS="| Metric | Value |
|--------|-------|
| **Total Tests** | ${TOTAL} |
| **Passed** | ${PASSED} ✅ |
| **Failed** | ${FAILED} ${FAILED_EMOJI} |
| **Skipped** | ${SKIPPED} |
| **Flaky** | ${FLAKY:-0} |
| **Duration** | ${DURATION_STR} |
| **Pass Rate** | ${PASS_RATE}% |"
if ((COUNTS_UNREADABLE > 0)); then
	METRICS="$(comment_unreadable_lines)"
	if [[ -n "$METRICS" && -n "$STRUCTURE_NOTES" ]]; then
		METRICS+=$'\n'
	fi
	METRICS+="${STRUCTURE_NOTES%$'\n'}"
elif ((${#COMMENT_UNREADABLE[@]} > 0)); then
	METRICS+=$'\n\n'"$(comment_unreadable_lines)"
fi
if [[ -n "$ERRORS_NOTE" ]]; then
	METRICS+=$'\n\n'"$ERRORS_NOTE"
fi

# Generate comment body
BODY="## 🧪 Playwright E2E Test Report

This PR has been analyzed using **lgtm-ci** - our Playwright E2E test workflow.

### 📊 Status: ${STATUS_EMOJI} ${STATUS_TEXT}

**Build:** ${TEST_STATUS_TEXT}

**Status:** ${TEST_STATUS_TEXT}

### 🧪 Test Results

${METRICS}"

# Add failed tests list (include timedOut and interrupted to match FAILED count)
if [[ "$SHOW_FAILED" == "true" && $FAILED -gt 0 ]]; then
	# A native report keeps the title on the spec and the project on the test:
	# label each failed test "<file> › <spec title> [<project>]". A test that
	# carries its own title (older report shapes) keeps that title.
	# shellcheck disable=SC2016 # jq program, not shell
	FAILED_TESTS=$(jq -r --argjson max "$MAX_FAILED" "${COMMENT_JQ_DEFS}"'
		[(.suites // []) | .. | objects | select(has("tests") and (.tests | type == "array"))
			| . as $owner | .tests[] | select(.status | comment_failed_status)
			| (.title // ([$owner.file, $owner.title] | map(select(type == "string" and . != "")) | join(" › ")))
				+ (if (.projectName // "") != "" then " [\(.projectName)]" else "" end)]
		| .[0:$max] | .[]' "$RESULTS_PATH" 2>/dev/null || echo "")
	if [[ -n "$FAILED_TESTS" ]]; then
		FAILED_TESTS_BLOCK="$(printf '%s' "$FAILED_TESTS" | comment_sanitize fence)"
		BODY="${BODY}

<details>
<summary>Failed Tests (showing up to ${MAX_FAILED})</summary>

${FAILED_TESTS_BLOCK}

</details>"
	fi
fi

if [[ -n "$SAFE_REPORT_URL" ]]; then
	BODY="${BODY}

### 🔎 View Full Reports

Public Report:

- [View Playwright HTML Report](${SAFE_REPORT_URL})"
fi

BODY="${BODY}

### 📋 Report Details
- **Generated:** ${GENERATED_DATE}
${COMMIT_LINE}"

if [[ -n "$BUILD_URL" ]]; then
	BODY="${BODY}

---

[View full build details](${BUILD_URL})"
fi

BODY="${BODY}

<sub>Generated by lgtm-ci Playwright E2E workflow</sub>"

set_github_output_multiline "body" "$BODY"
