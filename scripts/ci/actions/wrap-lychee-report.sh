#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
# Purpose: Wrap the lychee markdown report with scan context (status, counts,
#          what was scanned) so the published PR comment is self-explanatory.
#
# Environment variables expected:
#   LYCHEE_REPORT    - Path to the lychee markdown report (may be missing)
#   LYCHEE_OUTCOME   - Outcome of the lychee step (success, failure, skipped,
#                      cancelled); empty is treated as unknown
#   PATHS            - Comma-separated paths that were scanned
#   FILE_EXTENSIONS  - Comma-separated file extensions that were scanned
#   EXCLUDE_PATTERNS - Comma-separated exclude patterns
#   CHECK_EXTERNAL   - "true" when external HTTP(S) links were checked
#   TIMEOUT          - HTTP timeout in seconds
#   FAIL_ON_ERROR    - "true" when broken links fail the workflow
#   OUTPUT           - Optional output file (may equal LYCHEE_REPORT). When
#                      unset, the body is printed to stdout.
#
# Security: report content is untrusted data. It is only ever read with
# cat/awk and emitted through printf/cat (no eval, no expansion).

set -euo pipefail

LYCHEE_REPORT="${LYCHEE_REPORT:-lychee-report.md}"
LYCHEE_OUTCOME="${LYCHEE_OUTCOME:-}"
PATHS="${PATHS:-.}"
FILE_EXTENSIONS="${FILE_EXTENSIONS:-}"
EXCLUDE_PATTERNS="${EXCLUDE_PATTERNS:-}"
CHECK_EXTERNAL="${CHECK_EXTERNAL:-true}"
TIMEOUT="${TIMEOUT:-}"
FAIL_ON_ERROR="${FAIL_ON_ERROR:-true}"

# Extract the integer from a lychee summary table row such as
# "| 🚫 Errors | 3 |". Prints nothing when the row is absent.
table_count() {
	local label="$1" file="$2"
	awk -F'|' -v label="$label" '
		$2 ~ label {
			v = $3
			gsub(/[^0-9]/, "", v)
			if (v != "") { print v; exit }
		}
	' "$file"
}

build_body() {
	local has_report=false
	if [[ -f "$LYCHEE_REPORT" && -s "$LYCHEE_REPORT" ]]; then
		has_report=true
	fi

	printf '## 🔗 Link Check Report\n\n'

	if [[ "$has_report" != true ]]; then
		printf '### ⚠️ Status: NO REPORT PRODUCED\n\n'
		if [[ "$LYCHEE_OUTCOME" == "skipped" ]]; then
			printf 'The link check step was skipped, so no report was produced.\n\n'
		else
			printf 'The link check did not produce a report (step outcome: %s).\n\n' \
				"${LYCHEE_OUTCOME:-unknown}"
		fi
		printf '<sub>Generated by lgtm-ci link-check workflow</sub>\n'
		return 0
	fi

	local total errors
	total="$(table_count 'Total' "$LYCHEE_REPORT")"
	errors="$(table_count 'Errors' "$LYCHEE_REPORT")"

	local failed=false
	if [[ "$LYCHEE_OUTCOME" == "failure" || "$LYCHEE_OUTCOME" == "cancelled" ]]; then
		failed=true
	elif [[ -n "$errors" && "$errors" -gt 0 ]]; then
		failed=true
	fi

	if [[ "$failed" == true ]]; then
		printf '### 📊 Status: ❌ FAILED\n\n'
	else
		printf '### 📊 Status: ✅ PASSED\n\n'
	fi

	if [[ -n "$total" || -n "$errors" ]]; then
		printf '**Links checked:** %s | **Errors:** %s\n\n' \
			"${total:-unknown}" "${errors:-unknown}"
	else
		printf '_Link and error counts were not found in the report._\n\n'
	fi

	printf '### What was scanned\n\n'
	printf -- '- **Paths:** %s\n' "${PATHS:-.}"
	printf -- '- **File extensions:** %s\n' "${FILE_EXTENSIONS:-none specified}"
	printf -- '- **Excluded patterns:** %s\n' "${EXCLUDE_PATTERNS:-none}"
	if [[ "$CHECK_EXTERNAL" == "true" ]]; then
		printf -- '- **External link checks:** enabled\n'
	else
		printf -- '- **External link checks:** disabled\n'
	fi
	printf -- '- **Timeout:** %s\n' "${TIMEOUT:-default}"
	printf -- '- **Fail on error:** %s\n\n' "$FAIL_ON_ERROR"

	if [[ "$CHECK_EXTERNAL" != "true" ]]; then
		printf 'External link checking is disabled, so only in-repository links were verified; external URLs were not checked.\n\n'
	fi

	printf '<details>\n<summary>Original lychee report</summary>\n\n'
	cat "$LYCHEE_REPORT"
	printf '\n\n</details>\n\n'
	printf '<sub>Generated by lgtm-ci link-check workflow</sub>\n'
}

# Build into a temp file first: OUTPUT may be the same file as the input.
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
build_body >"$tmp"

if [[ -n "${OUTPUT:-}" ]]; then
	cat "$tmp" >"$OUTPUT"
else
	cat "$tmp"
fi
