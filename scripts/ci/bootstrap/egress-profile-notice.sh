#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
# Purpose: Report, on every hardened job of a non-block egress-profile copy, that egress is not enforced
#
# Source of truth for the inline "Report egress not enforced" step that
# scripts/ci/bootstrap/render-egress-profile.py writes in place of every
# "Verify harden-runner agent" step when it generates a copy with the audit
# or none egress profile (#1597). It is never part of this repository's own
# workflows, which stay block-only; it exists only in a generated copy.
#
# The step checks nothing about the harden-runner agent and claims nothing:
#   - It keeps the checks of verify-harden-runner-agent.sh that are not
#     about egress: RUNNER_ENVIRONMENT and RUNNER_OS must be known, and a
#     public repository on a self-hosted runner fails (#1552), whatever the
#     profile.
#   - audit: any egress-policy other than audit is rejected, so a copy
#     generated with the audit profile cannot be called as if it enforced
#     block (a copy that must enforce is generated with --profile block).
#   - none: harden-runner does not run, so egress-policy is ignored.
#   - It then writes a ::notice:: annotation and a job-summary line saying
#     what the profile does not do.
#
# Keep the body self-contained: no sourcing, no checkout, no network. The
# renderer copies the lines between the markers below into each generated
# workflow, so the copies cannot drift from this file.
#
# Environment variables:
#   EGRESS_PROFILE      - audit or none: written literally by the renderer
#   EGRESS_POLICY       - The egress-policy the job requested (audit only)
#   RUNNER_ENVIRONMENT  - github-hosted or self-hosted (set by the runner)
#   RUNNER_OS           - Linux, Windows or macOS (set by the runner)
#   REPOSITORY_PRIVATE  - github.event.repository.private: true, false or empty
#   GITHUB_STEP_SUMMARY - Step summary file; the notice line also goes there

set -euo pipefail

# lgtm-ci-inline:begin egress-profile-notice
# Generated by render-egress-profile.py (#1597). Source:
# scripts/ci/bootstrap/egress-profile-notice.sh
case "${RUNNER_ENVIRONMENT:-}/${RUNNER_OS:-}" in
  github-hosted/?*) ;;
  self-hosted/?*)
    # A public repository on a self-hosted runner is never intended (#1552):
    # fork pull requests could run there. Empty (no payload) is not public.
    if [[ "${REPOSITORY_PRIVATE:-}" == false ]]; then
      echo "::error title=public repository on self-hosted runner::a public" \
        "repository must not run on a self-hosted runner (RUNNER_OS=${RUNNER_OS}):" \
        "fork pull requests could run code there. Use a GitHub-hosted runner" \
        "(check the runner variable or runner-image input), or make the" \
        "repository internal or private"
      exit 1
    fi
    ;;
  *)
    echo "::error title=unknown runner::RUNNER_ENVIRONMENT and RUNNER_OS are required"
    exit 1
    ;;
esac
case "${EGRESS_PROFILE:-}" in
  audit)
    if [[ "${EGRESS_POLICY:-}" != audit ]]; then
      printf '::error title=egress-policy rejected::egress-policy %q is not accepted. ' \
        "${EGRESS_POLICY:-}"
      echo "This copy was generated with the audit egress profile: set egress-policy:" \
        "audit, or use a copy generated with --profile block for enforcement"
      exit 1
    fi
    line="Egress is not enforced in this job (audit egress profile): any step can"
    line+=" send data to any host. Where harden-runner runs, it only logs, and"
    line+=" reports resolved DNS names and connections to StepSecurity."
    ;;
  none)
    line="harden-runner is not run in this copy (egress profile none): there is no"
    line+=" egress control and no egress monitoring; any step can send data to any host."
    ;;
  *)
    printf '::error title=unknown egress profile::EGRESS_PROFILE %q is not audit or none\n' \
      "${EGRESS_PROFILE:-}"
    exit 1
    ;;
esac
echo "::notice title=egress not enforced::$line"
if [[ -n "${GITHUB_STEP_SUMMARY:-}" ]]; then
  echo "$line" >> "$GITHUB_STEP_SUMMARY"
fi
# lgtm-ci-inline:end egress-profile-notice
