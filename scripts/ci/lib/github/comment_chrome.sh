#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
# Purpose: Shared PR comment chrome (heading, status line, footer) so every
#          publisher renders the same frame around its content.
#
# Usage:
#   source "$(dirname "${BASH_SOURCE:-$0}")/comment_chrome.sh"
#   comment_chrome_heading "Link Check Report" "$(comment_chrome_result_status "$RESULT")"
#   ...body...
#   comment_chrome_footer "lgtm-ci link-check"
#
# Security: arguments are untrusted text. Everything is emitted through
# printf with a constant format string (no eval, no format-string use of
# caller data).

# Prevent multiple sourcing
[[ -n "${_LGTM_CI_GITHUB_COMMENT_CHROME_LOADED:-}" ]] && return 0
readonly _LGTM_CI_GITHUB_COMMENT_CHROME_LOADED=1

# Map an upstream job result to the status text used in the heading.
# Prints nothing for an empty or unrecognised result (no status line).
# Usage: comment_chrome_result_status "success"  ->  ✅ PASSED
comment_chrome_result_status() {
	case "${1:-}" in
	success) printf '%s' '✅ PASSED' ;;
	failure) printf '%s' '❌ FAILED' ;;
	cancelled) printf '%s' '⏭️ CANCELLED' ;;
	skipped) printf '%s' '⏭️ SKIPPED' ;;
	*) ;;
	esac
}

# Print the comment heading: "## <title>", then "### 📊 Status: <status>"
# (blank-line separated) when a non-empty status is given. Output ends with a
# single newline; the caller owns the blank line that follows.
# Usage: comment_chrome_heading "Title" ["✅ PASSED"]
comment_chrome_heading() {
	local title="${1:-}" status="${2:-}"
	printf '## %s\n' "$title"
	if [[ -n "$status" ]]; then
		printf '\n### 📊 Status: %s\n' "$status"
	fi
}

# Print the standard footer line.
# Usage: comment_chrome_footer "file breakdown"
comment_chrome_footer() {
	printf '<sub>Generated by %s workflow</sub>\n' "${1:-lgtm-ci}"
}

export -f comment_chrome_result_status comment_chrome_heading comment_chrome_footer
