"""Unit tests for ``comment_format.py`` and ``comment_test_report.py`` (#1678).

Both are in ``scripts/ci/lib``.

The formatter is given models directly (hostile values, a list over its
budget); the builder's command line and the generator's and poster's
handling of an unknown ``comment-format`` run as subprocesses.
"""

from __future__ import annotations

import importlib.util
import json
import subprocess
import sys
from pathlib import Path
from types import ModuleType
from typing import Any

import pytest
from assertpy import assert_that
from report_format_cases import PROJECT_ROOT, post, render

LIB = PROJECT_ROOT / "scripts" / "ci" / "lib"


def _load(name: str) -> ModuleType:
    """Import a module from ``scripts/ci/lib`` by file."""
    if str(LIB) not in sys.path:
        sys.path.insert(0, str(LIB))
    spec = importlib.util.spec_from_file_location(name, LIB / f"{name}.py")
    if spec is None or spec.loader is None:
        raise ImportError(name)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


FORMAT = _load("comment_format")


def _model(**changes: object) -> dict[str, Any]:
    """Return a small valid model with ``changes`` applied."""
    model: dict[str, Any] = {
        "schema": "comment.v1",
        "kind": "test-report",
        "title": {"icon": "🧪", "text": "Suite"},
        "status": {"level": "passed", "emoji": "✅", "label": "PASSED"},
        "summary": [[{"text": "1 passed"}]],
        "blocks": [],
        "facts": [],
        "links": [],
        "footer": "Generated by Suite workflow",
    }
    model.update(changes)
    return model


@pytest.mark.parametrize("fmt", ["compact", "table"])
def test_hostile_model_values_are_inert(fmt: str) -> None:
    """Every model string is sanitised: no HTML, mention, marker or unsafe link."""
    hostile = "@team <script> | x <!-- lgtm-ci:history:start --> [a](javascript:b)"
    unsafe = {"label": hostile, "url": "javascript:alert(1)"}
    table = {
        "type": "table",
        "id": "tests",
        "title": hostile,
        "columns": [{"label": hostile}],
        "rows": [{"label": hostile, "cells": [{"text": hostile, "mark": hostile}]}],
    }
    model = _model(
        title={"icon": "🧪", "text": hostile},
        status={"level": "failed", "emoji": "❌", "label": hostile},
        summary=[[{"text": hostile, "code": True}, {"text": hostile, "strong": True}]],
        blocks=[table, {"type": "notice", "spans": [{"text": hostile}]}],
        facts=[{"label": hostile, "value": {"link": unsafe}}],
        links=[{"label": hostile, "url": "https://user@evil.example/"}],
        footer=hostile,
    )

    body = FORMAT.render(model, fmt)

    assert_that(body).does_not_contain(
        "<script>", "<!-- lgtm-ci:", "](javascript", "](https://user@", "@team"
    )


def test_table_cells_cannot_split_a_row() -> None:
    """A pipe in a cell is escaped, so a row keeps its column count."""
    table = {
        "type": "table",
        "id": "t",
        "title": "T",
        "columns": [{"label": "A"}, {"label": "B"}],
        "rows": [{"label": "r", "cells": [{"text": "a|b"}, {"text": "c\\|d"}]}],
    }

    body = FORMAT.render(_model(blocks=[table]), "table")
    row = body.splitlines()[4]

    assert_that(row.replace("\\|", "").count("|")).is_equal_to(3)


def test_list_keeps_within_its_budget_and_counts_the_rest() -> None:
    """A list stops at its byte budget; every item not shown is in 'and N more'."""
    items = [{"code": f"id{n}" + "<" * 300, "text": "<" * 300} for n in range(50)]
    block = {"type": "list", "summary": "S", "items": items, "more": 7}

    body = FORMAT.render(_model(blocks=[block]), "table")
    listed = body[body.index("<details>") : body.index("</details>")]
    shown = listed.count("\n- `")

    budget = FORMAT.LIST_BUDGET_BYTES + 64
    assert_that(len(listed.encode("utf-8"))).is_less_than_or_equal_to(budget)
    assert_that(shown).is_less_than(50)
    assert_that(listed).contains(f"- and {50 - shown + 7} more")


def test_a_long_or_escaped_row_label_reads_this_run() -> None:
    """A row label longer than its cap, or one that needs escaping, is replaced."""
    rows = [
        {"label": "x" * 40, "cells": [{"count": 1}]},
        {"label": "a_<b", "cells": [{"count": 2}]},
    ]
    columns = [{"label": "N"}]
    table = {"type": "table", "id": "t", "title": "T", "columns": columns, "rows": rows}

    body = FORMAT.render(_model(blocks=[table]), "compact")

    assert_that(body).contains("| this run | 1 |", "| this run | 2 |")


def test_render_refuses_an_unknown_format() -> None:
    """Only compact and table are laid out here; classic stays the renderer's own."""
    with pytest.raises(ValueError, match="unknown comment format"):
        FORMAT.render(_model(), "classic")


def _builder(
    *args: str,
    env: dict[str, str] | None = None,
) -> subprocess.CompletedProcess[str]:
    """Run the builder's command line."""
    return subprocess.run(
        [sys.executable, "-I", "-S", str(LIB / "comment_test_report.py"), *args],
        capture_output=True,
        text=True,
        check=False,
        env=env or {},
    )


@pytest.mark.parametrize(
    "args",
    [
        (),
        ("--format",),
        ("--format", "classic"),
        ("--format", "Compact"),
        ("--out", "x"),
        ("--format", "table", "--x", "y"),
    ],
)
def test_builder_usage_errors_exit_2(args: tuple[str, ...]) -> None:
    """A missing or unknown format, or an unknown flag, is a usage error."""
    done = _builder(*args)

    assert_that(done.returncode).is_equal_to(2)
    assert_that(done.stderr).starts_with("usage:")
    assert_that(done.stdout).is_empty()


def test_builder_internal_error_exits_1_without_a_comment(tmp_path: Path) -> None:
    """A comment that cannot be written fails with an annotation, never a fallback."""
    done = _builder("--format", "compact", "--out", str(tmp_path))

    assert_that(done.returncode).is_equal_to(1)
    assert_that(done.stderr).contains("::error title=comment-format::")


def test_builder_reads_unreadable_counts_as_unreadable(tmp_path: Path) -> None:
    """A count that is not plain digits never becomes 0 and never passes."""
    model_file = tmp_path / "model.json"
    env = {
        "REPORT_STATUS_EMOJI": "✅",
        "REPORT_STATUS_TEXT": "PASSED",
        "REPORT_COUNTS_AVAILABLE": "true",
        "REPORT_TOTAL": "-1",
        "REPORT_PASSED": "3",
    }

    done = _builder("--format", "compact", "--model", str(model_file), env=env)
    model = json.loads(model_file.read_text(encoding="utf-8"))

    assert_that(done.returncode).is_equal_to(0)
    assert_that(model["status"]["level"]).is_equal_to("warning")
    assert_that(model["summary"][0]).is_equal_to([{"text": "test counts unreadable"}])
    assert_that(done.stdout).contains("<details open>").does_not_contain("| Total |")


@pytest.mark.parametrize(
    "value",
    ["Compact", "markdown", "classic ", "compact\n::warning::x"],
)
def test_generator_fails_on_an_unknown_format(tmp_path: Path, value: str) -> None:
    """An unknown comment-format fails before anything is written, unechoed."""
    rendered = render(tmp_path, "passed", value)

    assert_that(rendered.returncode).is_equal_to(1)
    assert_that(rendered.body).is_empty()
    assert_that(rendered.outputs).is_empty()
    assert_that(rendered.stderr).contains(
        "::error title=unknown comment-format::"
    ).does_not_contain("::warning::x")


def test_poster_fails_on_an_unknown_format(tmp_path: Path) -> None:
    """The poster refuses an unknown comment-format and posts nothing."""
    posted, code, log = post(tmp_path, "## Report\n", "Environment: staging\n", "wide")

    assert_that(code).is_equal_to(1)
    assert_that(posted).is_empty()
    assert_that(log).contains("::error title=unknown comment-format::")
