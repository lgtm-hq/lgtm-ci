"""Every reusable workflow has exactly one hand-edited source (#1356).

A ``reusable-*.yml`` is a facade (it declares a read-only or overlay variant),
generated from a facade by ``scripts/ci/workflows/sync-readonly-variants.sh``
(GENERATED header on line 1), or a standalone file listed in
``scripts/ci/workflows/standalone-reusables.txt``. Anything else is a
hand-maintained copy that nothing keeps in step with its original, so it
fails here. The list must never hold the two near-copies #1356 removed.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from assertpy import assert_that

PROJECT_ROOT = Path(__file__).resolve().parents[2]
WORKFLOWS_DIR = PROJECT_ROOT / ".github" / "workflows"
ALLOWLIST = PROJECT_ROOT / "scripts" / "ci" / "workflows" / "standalone-reusables.txt"
GENERATED_MARK = "# GENERATED by scripts/ci/workflows/sync-readonly-variants.sh"
VARIANT_MARKS = ("# lgtm-ci-readonly-variant:", "# lgtm-ci-overlay-variant:")
UNLISTED = "neither a facade, generated, nor listed in standalone-reusables.txt"
FORMER_TWINS = (
    "reusable-release-multi-ecosystem.yml",
    "reusable-test-node-custom.yml",
)


def read_allowlist(path: Path) -> list[str]:
    """Return the allowlist's entries in file order, comments and blanks dropped."""
    lines = path.read_text(encoding="utf-8").splitlines()
    return [line.strip() for line in lines if line.strip() and not line.startswith("#")]


def kind_of(path: Path) -> str:
    """Classify one workflow as ``generated``, ``facade`` or ``hand``."""
    lines = path.read_text(encoding="utf-8").splitlines()
    if lines and lines[0].startswith(GENERATED_MARK):
        return "generated"
    if any(line.startswith(VARIANT_MARKS) for line in lines):
        return "facade"
    return "hand"


def source_problems(workflows_dir: Path, allowlist: list[str]) -> list[str]:
    """Return one line per reusable without a single source, and per stale entry."""
    paths = sorted(workflows_dir.glob("reusable-*.yml"))
    kinds = {path.name: kind_of(path) for path in paths}
    listed = set(allowlist)
    problems = [
        f"{name}: {UNLISTED}"
        for name, kind in kinds.items()
        if kind == "hand" and name not in listed
    ]
    for name in allowlist:
        if name not in kinds:
            problems.append(f"{name}: listed but missing")
        elif kinds[name] != "hand":
            problems.append(f"{name}: listed but {kinds[name]}")
    return problems


def write_workflows(directory: Path, files: dict[str, str]) -> Path:
    """Write workflow files into ``directory`` and return it."""
    for name, text in files.items():
        (directory / name).write_text(text, encoding="utf-8")
    return directory


def test_every_committed_reusable_has_one_source() -> None:
    """Each committed reusable is a facade, generated, or listed as standalone."""
    problems = source_problems(WORKFLOWS_DIR, read_allowlist(ALLOWLIST))

    assert_that(problems).is_empty()


@pytest.mark.parametrize("twin", FORMER_TWINS)
def test_allowlist_never_lists_a_former_twin(twin: str) -> None:
    """The near-copies #1356 removed or generated stay off the standalone list."""
    assert_that(read_allowlist(ALLOWLIST)).does_not_contain(twin)


def test_allowlist_is_sorted_and_unique() -> None:
    """Entries are sorted once each, so a new one is a visible one-line diff."""
    entries = read_allowlist(ALLOWLIST)

    assert_that(entries).is_equal_to(sorted(set(entries)))


def test_unlisted_hand_maintained_copy_fails(tmp_path: Path) -> None:
    """A new hand-written reusable that is not listed is reported by name."""
    workflows = write_workflows(
        tmp_path,
        {
            "reusable-demo.yml": (
                "---\nname: Demo\n# lgtm-ci-readonly-variant: reusable-demo-run.yml\n"
            ),
            "reusable-demo-run.yml": f"{GENERATED_MARK} from\n---\nname: Demo run\n",
            "reusable-demo-copy.yml": "---\nname: Demo copy\n",
        },
    )

    assert_that(source_problems(workflows, [])).is_equal_to(
        [f"reusable-demo-copy.yml: {UNLISTED}"],
    )


def test_listed_hand_maintained_file_passes(tmp_path: Path) -> None:
    """A listed standalone reusable is accepted."""
    workflows = write_workflows(tmp_path, {"reusable-solo.yml": "---\nname: Solo\n"})

    assert_that(source_problems(workflows, ["reusable-solo.yml"])).is_empty()


def test_generated_header_off_line_one_is_not_generated(tmp_path: Path) -> None:
    """The GENERATED header counts only on line 1, as the generator writes it."""
    workflows = write_workflows(
        tmp_path,
        {"reusable-fake.yml": f"---\nname: Fake\n{GENERATED_MARK}\n"},
    )

    assert_that(source_problems(workflows, [])).is_length(1)


@pytest.mark.parametrize(
    ("files", "expected"),
    [
        ({}, "reusable-gone.yml: listed but missing"),
        (
            {"reusable-gone.yml": f"{GENERATED_MARK} from\n---\nname: Gone\n"},
            "reusable-gone.yml: listed but generated",
        ),
        (
            {
                "reusable-gone.yml": (
                    "---\nname: Gone\n# lgtm-ci-overlay-variant: reusable-gone-x.yml\n"
                ),
            },
            "reusable-gone.yml: listed but facade",
        ),
    ],
)
def test_stale_allowlist_entry_fails(
    tmp_path: Path,
    files: dict[str, str],
    expected: str,
) -> None:
    """An entry whose file is gone, generated or a facade must be deleted."""
    workflows = write_workflows(tmp_path, files)

    assert_that(source_problems(workflows, ["reusable-gone.yml"])).contains(expected)
